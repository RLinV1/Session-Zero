import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { filterStateForViewer, sceneState, tableOf, type PreparationEdit } from "@vtt/shared";
import { startServer, type TestClient } from "./helpers";
let server: Awaited<ReturnType<typeof startServer>>;
const clients: TestClient[] = [];
beforeEach(async () => { server = await startServer(); });
afterEach(async () => { clients.splice(0).forEach((client) => client.close()); await server.close(); });
async function connect(creds: Parameters<typeof server.connect>[0]) { const client = await server.connect(creds); clients.push(client); return client; }
const ok = async (promise: Promise<unknown>) => expect(await promise).toMatchObject({ type: "ack" });

describe("scene switching over real sockets", () => {
  it("saves large private terrain preparations without changing or disclosing the live board (FR-TAC-03)", async () => {
    const creds = await server.createRoom();
    const gm = await connect(creds);
    const player = await connect(await server.join(creds.inviteCode, "Alice"));
    await ok(gm.command({ type: "scene.setMap", map: { url: "/live", width: 1000, height: 1000 } }));
    const live = structuredClone(tableOf(gm.state));
    await ok(gm.command({ type: "scene.create", name: "Private terrain", activate: false }));
    const sceneId = Object.keys(gm.state.savedScenes!)[0]!;
    await ok(gm.command({ type: "scene.prepare", sceneId, command: { type: "scene.setMap", map: { url: "/private", width: 1000, height: 1000 }, grid: { cellSize: 10, offsetX: 0, offsetY: 0, unitsPerCell: 5, unitLabel: "ft" } } }));
    const state = sceneState(gm.state, sceneId)!;
    const context = { boardEpoch: state.boardEpoch!, revision: state.terrainRevision! };
    const base = Array.from({ length: 2000 }, (_, i) => ({ row: Math.floor(i / 100), start: i % 100, end: i % 100, kind: i % 2 ? "blocked" as const : "difficult" as const }));
    const edits: PreparationEdit[] = [];
    for (let start = 0; start < base.length; start += 250) edits.push({ type: "terrain.paint", layerId: "base", context: { ...context, revision: context.revision + start / 250 }, paint: base.slice(start, start + 250) });
    edits.push({ type: "scene.setIsometric", enabled: true });
    const command = { type: "scene.prepare", sceneId, command: { type: "scene.savePreparation", expectedSceneId: sceneId, expectedMapUrl: "/private", context, edits } };
    expect(JSON.stringify(command).length).toBeGreaterThan(64 * 1024);
    const save = () => fetch(`${server.base}/api/rooms/${creds.roomId}/preparation`, {
      method: "POST", headers: { authorization: `Bearer ${creds.guestToken}`, "content-type": "application/json" }, body: JSON.stringify(command),
    });
    const response = await save();
    expect(response.status).toBe(200);
    const { seq } = await response.json() as { seq: number };
    await gm.waitForSeq(seq); await player.waitForSeq(seq);
    expect(tableOf(gm.state)).toEqual(live);
    expect(gm.state.savedScenes![sceneId]!.table.terrain?.base).toEqual(base);
    expect(gm.state.savedScenes![sceneId]!.table.scene.isometric).toBe(true);
    expect(player.state.savedScenes ?? {}).toEqual({});
    expect(JSON.stringify(player.state)).not.toContain("Private terrain");
    const events = await server.store.loadEvents(creds.roomId);
    expect(events.at(-1)!.event.type).toBe("ScenePrepared");
    expect((await save()).status).toBe(409);
    expect(await server.store.loadEvents(creds.roomId)).toEqual(events);
    const reconnect = await connect(creds);
    expect(reconnect.state.savedScenes![sceneId]!.table.terrain?.base).toEqual(base);
  });

  it("copies live progress privately and keeps later changes independent", async () => {
    const creds = await server.createRoom();
    const gm = await connect(creds);
    const player = await connect(await server.join(creds.inviteCode, "Alice"));
    await ok(gm.command({ type: "token.create", name: "Guard", position: { x: 35, y: 35 }, stats: { hp: 3, maxHp: 10, ac: null } }));
    const tokenId = Object.keys(gm.state.tokens)[0]!;
    await ok(gm.command({ type: "scene.create", name: "Private copy", activate: false }));
    const sceneId = Object.keys(gm.state.savedScenes!)[0]!;
    await ok(gm.command({ type: "scene.copyCurrent", sceneId }));
    await ok(gm.command({ type: "scene.prepare", sceneId, command: { type: "token.setStats", tokenId, stats: { hp: 1, maxHp: 10, ac: null } } }));
    await player.waitForSeq(gm.seq);
    expect(gm.state.tokens[tokenId]!.stats.hp).toBe(3);
    expect(player.state.tokens[tokenId]!.stats.hp).toBe(3);
    expect(gm.state.savedScenes![sceneId]!.table.tokens[tokenId]!.stats.hp).toBe(1);
    expect(await player.command({ type: "scene.copyCurrent", sceneId })).toMatchObject({ type: "rejected", code: "forbidden" });
    await ok(gm.command({ type: "token.move", tokenId, to: { x: 105, y: 35 } }));
    const reconnect = await connect(creds);
    expect(reconnect.state.savedScenes![sceneId]!.table.tokens[tokenId]!.position.x).toBe(35);
    expect(reconnect.state.savedScenes![sceneId]!.table.tokens[tokenId]!.stats.hp).toBe(1);
  });
  it("applies a room checkpoint only to the new private scene", async () => {
    const creds = await server.createRoom();
    const gm = await connect(creds);
    const player = await connect(await server.join(creds.inviteCode, "Alice"));
    await ok(gm.command({ type: "token.create", name: "Guard", position: { x: 35, y: 35 }, stats: { hp: 3, maxHp: 10, ac: null } }));
    const tokenId = Object.keys(gm.state.tokens)[0]!;
    await ok(gm.command({ type: "checkpoint.create", name: "Before ambush" }));
    const checkpointId = gm.state.checkpoints[0]!.id;
    await ok(gm.command({ type: "token.move", tokenId, to: { x: 105, y: 35 } }));
    await ok(gm.command({ type: "scene.create", name: "Checkpoint scene", activate: false }));
    const sceneId = Object.keys(gm.state.savedScenes!)[0]!;
    await ok(gm.command({ type: "scene.prepare", sceneId, command: { type: "checkpoint.restore", checkpointId } }));
    await player.waitForSeq(gm.seq);
    expect(gm.state.tokens[tokenId]!.position.x).toBe(105);
    expect(player.state.tokens[tokenId]!.position.x).toBe(105);
    expect(gm.state.savedScenes![sceneId]!.table.tokens[tokenId]!.position.x).toBe(35);
    expect(gm.state.savedScenes![sceneId]!.table.tokens[tokenId]!.stats.hp).toBe(3);
    expect(await gm.command({ type: "scene.prepare", sceneId, command: { type: "checkpoint.restore", checkpointId: "another-room" } })).toMatchObject({ type: "rejected", code: "not_found" });
  });
  it("keeps players on the live board throughout private creation and preparation", async () => {
    const creds = await server.createRoom();
    const gm = await connect(creds);
    const player = await connect(await server.join(creds.inviteCode, "Alice"));
    await ok(gm.command({ type: "token.create", name: "Live guard", position: { x: 35, y: 35 } }));
    const live = tableOf(gm.state);
    await ok(gm.command({ type: "scene.create", name: "Private cellar", activate: false }));
    const sceneId = Object.keys(gm.state.savedScenes!)[0]!;
    expect(tableOf(gm.state)).toEqual(live);
    const prepare = (command: import("@vtt/shared").CommandInput) => gm.command({ type: "scene.prepare", sceneId, command: command as Exclude<import("@vtt/shared").CommandInput, { type: "scene.prepare" }> });
    await ok(prepare({ type: "scene.setMap", expectedSceneId: sceneId, map: { url: "/private.png", width: 700, height: 700 } }));
    await ok(prepare({ type: "token.create", name: "Private rat", position: { x: 35, y: 35 } }));
    await player.waitForSeq(gm.seq);
    expect(tableOf(player.state).tokens).toEqual(live.tokens);
    expect(player.state.scene.map).toBeNull();
    expect(player.rawLog.join(" ")).not.toContain("Private");
    expect(player.rawLog.join(" ")).not.toContain("private.png");
    expect(await player.command({ type: "scene.prepare", sceneId, command: { type: "token.create", name: "Intruder", position: { x: 35, y: 35 } } })).toMatchObject({ type: "rejected", code: "forbidden" });
    const reconnected = await connect(creds);
    expect(Object.values(reconnected.state.savedScenes![sceneId]!.table.tokens)[0]!.name).toBe("Private rat");
    await ok(gm.command({ type: "scene.switch", sceneId }));
    await player.waitForSeq(gm.seq);
    expect(Object.values(player.state.tokens)[0]!.name).toBe("Private rat");
    expect(player.state.scene.map?.url).toBe("/private.png");
    expect(await prepare({ type: "token.create", name: "Stale edit", position: { x: 35, y: 35 } })).toMatchObject({ type: "rejected", code: "invalid" });
  });
  it("autosaves both locations, filters every switch and reloads saved progress after a server restart", async () => {
    const gmCreds = await server.createRoom();
    const gm = await connect(gmCreds);
    const playerCreds = await server.join(gmCreds.inviteCode, "Alice");
    const player = await connect(playerCreds);
    await ok(gm.command({ type: "scene.rename", sceneId: "initial", name: "Secret tavern" }));
    await ok(gm.command({ type: "token.create", name: "Rogue", ownerIds: [player.participantId], position: { x: 35, y: 35 }, stats: { hp: 3, maxHp: 10, ac: null } }));
    await ok(gm.command({ type: "token.create", name: "Secret monster", hidden: true, position: { x: 315, y: 315 } }));
    const tavern = tableOf(gm.state);
    await ok(gm.command({ type: "scene.create", name: "Secret cellar" }));
    const cellarId = gm.state.activeSceneId!;
    await player.waitForSeq(gm.seq);
    expect(player.state.tokens).toEqual({});
    expect(player.state.savedScenes).toEqual({});
    expect(player.state.sceneNames).toEqual({});
    await ok(gm.command({ type: "token.create", name: "Rat", position: { x: 35, y: 35 } }));
    await ok(player.command({ type: "chat.send", text: "Moving downstairs" }));
    await gm.waitForSeq(player.seq);
    const cellar = tableOf(gm.state);
    await ok(gm.command({ type: "scene.switch", sceneId: "initial" }));
    await player.waitForSeq(gm.seq);
    expect(tableOf(gm.state)).toEqual(tavern);
    expect(player.state).toEqual(filterStateForViewer(gm.state, gm.state.participants[player.participantId]!));
    expect(gm.state.chat.at(-1)?.text).toBe("Moving downstairs");
    expect(player.rawLog.join(" ")).not.toContain("Secret");
    await ok(gm.command({ type: "scene.switch", sceneId: cellarId }));
    expect(tableOf(gm.state)).toEqual(cellar);
    const store = server.store;
    clients.splice(0).forEach((client) => client.close());
    await server.close();
    server = await startServer(store);
    const resumed = await connect(gmCreds);
    expect(tableOf(resumed.state)).toEqual(cellar);
    await ok(resumed.command({ type: "scene.switch", sceneId: "initial" }));
    expect(tableOf(resumed.state)).toEqual(tavern);
    const reconnect = await connect(playerCreds);
    expect(reconnect.rawLog.join(" ")).not.toContain("Secret");
    expect(reconnect.state.tokens).toHaveProperty(Object.keys(tavern.tokens)[0]!);
  });

  it("keeps checkpoint restores in the current scene and refuses player management", async () => {
    const creds = await server.createRoom();
    const gm = await connect(creds);
    const player = await connect(await server.join(creds.inviteCode, "Alice"));
    expect(await player.command({ type: "scene.create", name: "Forbidden" })).toMatchObject({ type: "rejected", code: "forbidden" });
    await ok(gm.command({ type: "token.create", name: "Tavern guard", position: { x: 35, y: 35 } }));
    const tavern = tableOf(gm.state);
    await ok(gm.command({ type: "scene.create", name: "Cellar" }));
    await ok(gm.command({ type: "checkpoint.create", name: "Empty cellar" }));
    await ok(gm.command({ type: "token.create", name: "Rat", position: { x: 35, y: 35 } }));
    await ok(gm.command({ type: "checkpoint.restore", checkpointId: gm.state.checkpoints[0]!.id }));
    expect(gm.state.tokens).toEqual({});
    expect(gm.state.sceneNames).toEqual({ initial: "Scene 1", [gm.state.activeSceneId!]: "Cellar" });
    await ok(gm.command({ type: "scene.switch", sceneId: "initial" }));
    expect(tableOf(gm.state)).toEqual(tavern);
  });

  it("does not restore a revoked participant's access from an inactive scene", async () => {
    const creds = await server.createRoom();
    const gm = await connect(creds);
    const playerCreds = await server.join(creds.inviteCode, "Alice");
    const player = await connect(playerCreds);
    await ok(gm.command({ type: "token.create", name: "Rogue", ownerIds: [player.participantId], position: { x: 35, y: 35 } }));
    await ok(gm.command({ type: "scene.create", name: "Cellar" }));
    await ok(gm.command({ type: "participant.revoke", participantId: player.participantId }));
    await ok(gm.command({ type: "scene.switch", sceneId: "initial" }));
    expect(gm.state.participants[player.participantId]!.revoked).toBe(true);
    await expect(server.connect(playerCreds)).rejects.toThrow();
  });
});
